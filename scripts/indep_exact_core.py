def coordinate_names(s):
    """All names a{i},{j} (j < i) and b{i}, 1-based, in a fixed order."""
    names = []
    for i in range(2, s + 1):
        for j in range(1, i):
            names.append(f"a{i},{j}")
    for i in range(1, s + 1):
        names.append(f"b{i}")
    return names


def build_tableau(system, lookup, conv):
    """Build (A, b) over a ring.

    lookup(name) -> ring element for free coordinates; fixed coordinates are converted from
    their rational strings with conv.  Every strictly-lower coupling and every weight must be
    either fixed or free; anything on or above the diagonal must be absent or fixed to zero.
    Returns (A, b, report dict).
    """
    s = int(system["s"])
    fixed = system["fixed"]
    free = list(system["free"])
    free_set = set(free)
    zero = conv(0)
    A = [[zero for _ in range(s)] for _ in range(s)]
    b = [zero for _ in range(s)]
    n_fixed = n_free = 0
    for name in coordinate_names(s):
        if name in fixed:
            val = conv(Fraction(str(fixed[name])))
            n_fixed += 1
        elif name in free_set:
            val = lookup(name)
            n_free += 1
        else:
            raise ValueError(f"coordinate {name} is neither fixed nor free")
        if name[0] == "a":
            i, j = (int(x) for x in name[1:].split(","))
            A[i - 1][j - 1] = val
        else:
            b[int(name[1:]) - 1] = val
    # anything else mentioned in fixed or free must be an upper-triangular zero or an error
    extra = []
    for name in list(fixed) + free:
        if name[0] == "a":
            i, j = (int(x) for x in name[1:].split(","))
            if j >= i:
                if name in free_set or Fraction(str(fixed[name])) != 0:
                    raise ValueError(f"non-zero coefficient on or above the diagonal: {name}")
                extra.append(name)
        elif name[0] == "b":
            pass
        else:
            raise ValueError(f"unknown coordinate name {name}")
    return A, b, {"s": s, "n_fixed": n_fixed, "n_free": n_free,
                  "n_free_listed": len(free), "upper_zeros_listed": extra}


def summarize_residuals(res, zero_test=_is_zero):
    """Group residuals by order: returns dict order -> (n_trees, n_failed, [failed tree strs])."""
    out = {}
    for tree, k, r in res:
        n, nf, fl = out.get(k, (0, 0, []))
        n += 1
        if not zero_test(r):
            nf += 1
            fl.append(tree_str(tree))
        out[k] = (n, nf, fl)
    return out
