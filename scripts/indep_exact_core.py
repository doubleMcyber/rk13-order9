"""Independent exact verifier, core module (written 2026-10-31 for PREREG line 6).

Written from first principles after Butcher, Numerical Methods for Ordinary Differential
Equations (rooted trees, elementary weights, densities), without reading any lane file that
implements trees, order conditions, tableaux or verification.

Contents
  * rooted trees as canonical nested tuples (a tree is the sorted tuple of its subtrees;
    the single vertex is the empty tuple), generated by size and checked against A000081;
  * order(t) = number of vertices, density gamma(t) = order(t) * prod gamma(children);
  * elementary weight Phi(t) = sum_i b_i phi_i(t), with the stage vectors built recursively,
    phi_i(leaf) = 1 and phi_i([t_1 ... t_k]) = prod_j (A phi(t_j))_i.  With this convention
    the nodes c = A 1 never enter explicitly: the row-sum convention is built in;
  * the order condition for tree t: Phi(t) = 1 / gamma(t);
  * an exact arithmetic class KElem for the ring K = Q[t, y] / (F(t), y^2 - P1(t) y - P0(t)),
    elements u(t) + v(t) y with u, v in Q[t] reduced modulo F (python-flint fmpq_poly), and
    the degenerate case P0 = P1 = 0 with v = 0 for a simple quotient Q[theta]/(f).

The residual functions are generic: they only use +, -, * and a conversion from rationals, so
the same code runs over Fractions (controls), over K (the exact check) and over mpmath mpf
(the floating sanity check).
"""

from fractions import Fraction
from itertools import product as iproduct

# ----------------------------------------------------------------------------------------
# Rooted trees
# ----------------------------------------------------------------------------------------

LEAF = ()

_TREES_BY_SIZE = {1: [LEAF]}


def _partitions(n, max_part):
    """Integer partitions of n into parts <= max_part, as non-increasing tuples."""
    if n == 0:
        yield ()
        return
    for p in range(min(n, max_part), 0, -1):
        for rest in _partitions(n - p, p):
            yield (p,) + rest


def trees_of_size(n):
    """All rooted trees with exactly n vertices, as canonical tuples (sorted children)."""
    if n in _TREES_BY_SIZE:
        return _TREES_BY_SIZE[n]
    found = set()
    for parts in _partitions(n - 1, n - 1):
        choices = [trees_of_size(p) for p in parts]
        for combo in iproduct(*choices):
            found.add(tuple(sorted(combo)))
    result = sorted(found)
    _TREES_BY_SIZE[n] = result
    return result


def trees_up_to(p):
    """All rooted trees with at most p vertices, in order of size, then canonical order."""
    out = []
    for n in range(1, p + 1):
        out.extend(trees_of_size(n))
    return out


def order(tree):
    return 1 + sum(order(c) for c in tree)


def density(tree):
    g = order(tree)
    for c in tree:
        g *= density(c)
    return g


def tree_str(tree):
    """Bracket notation: 't' is the single vertex, [t t] a root with two leaf children."""
    if tree == LEAF:
        return "t"
    return "[" + "".join(tree_str(c) for c in tree) + "]"


A000081 = [1, 1, 2, 4, 9, 20, 48, 115, 286, 719]  # rooted trees with n = 1, 2, ... vertices


def check_tree_counts(p):
    """Return (counts list, total) and raise if the counts disagree with A000081."""
    counts = [len(trees_of_size(n)) for n in range(1, p + 1)]
    if counts != A000081[:p]:
        raise AssertionError(f"tree counts {counts} differ from A000081 {A000081[:p]}")
    return counts, sum(counts)


# ----------------------------------------------------------------------------------------
# Elementary weights and order conditions (generic ring)
# ----------------------------------------------------------------------------------------

def _is_zero(x):
    f = getattr(x, "is_zero", None)
    if f is not None:
        return f()
    return x == 0


class OrderConditions:
    """Elementary weights for a tableau (A, b) over a ring given by a conversion function.

    A: list of s lists of s ring elements (full square, strictly lower triangular expected but
       not assumed: the code multiplies out whatever it is given).
    b: list of s ring elements.
    conv: rational (Fraction or int) -> ring element.
    """

    def __init__(self, A, b, conv):
        self.A = A
        self.b = b
        self.s = len(b)
        self.conv = conv
        self.one = conv(1)
        self.zero = conv(0)
        self._phi = {}    # tree -> stage vector (list of s ring elements)
        self._Aphi = {}   # tree -> A times stage vector
        # skip exact zeros of A in matrix-vector products (an optimisation only)
        self._nz = [[j for j in range(self.s) if not _is_zero(A[i][j])] for i in range(self.s)]

    def stage_vector(self, tree):
        if tree in self._phi:
            return self._phi[tree]
        if tree == LEAF:
            vec = [self.one] * self.s
        else:
            vec = None
            for child in tree:
                w = self.A_times(child)
                vec = list(w) if vec is None else [vec[i] * w[i] for i in range(self.s)]
        self._phi[tree] = vec
        return vec

    def A_times(self, tree):
        if tree in self._Aphi:
            return self._Aphi[tree]
        v = self.stage_vector(tree)
        out = []
        for i in range(self.s):
            acc = self.zero
            for j in self._nz[i]:
                acc = acc + self.A[i][j] * v[j]
            out.append(acc)
        self._Aphi[tree] = out
        return out

    def weight(self, tree):
        v = self.stage_vector(tree)
        acc = self.zero
        for i in range(self.s):
            acc = acc + self.b[i] * v[i]
        return acc

    def residual(self, tree):
        return self.weight(tree) - self.conv(Fraction(1, density(tree)))

    def residuals_up_to(self, p):
        """List of (tree, order, residual) for every tree with at most p vertices."""
        return [(t, order(t), self.residual(t)) for t in trees_up_to(p)]

    def residuals_pruned(self, p, progress=None):
        """Same result as residuals_up_to(p) with a smaller cache: trees of order p are never
        children, so their stage vectors are not kept, and for smaller trees the stage vector is
        dropped as soon as A times it has been cached.  progress(order, n_trees, n_nonzero,
        seconds) is called after each order."""
        import time as _time
        out = []
        for k in range(1, p + 1):
            tk = _time.time()
            nz = 0
            for tree in trees_of_size(k):
                r = self.residual(tree)
                if not _is_zero(r):
                    nz += 1
                out.append((tree, k, r))
                if k < p:
                    self.A_times(tree)
                self._phi.pop(tree, None)
            if progress is not None:
                progress(k, len(trees_of_size(k)), nz, _time.time() - tk)
        return out


# ----------------------------------------------------------------------------------------
# Exact arithmetic in K = Q[t, y] / (F(t), y^2 - P1(t) y - P0(t))
# ----------------------------------------------------------------------------------------

try:
    import flint
    from flint import fmpq, fmpq_poly
except ImportError:  # pragma: no cover
    flint = None


def frac_to_fmpq(x):
    x = Fraction(x)
    return fmpq(x.numerator, x.denominator)


def fmpq_to_frac(x):
    return Fraction(int(x.p), int(x.q))


def poly_from_strings(coeffs):
    """fmpq_poly from a list of rational strings, constant term first."""
    return fmpq_poly([frac_to_fmpq(Fraction(str(c))) for c in coeffs])


class KRing:
    """The ring K.  F must have positive degree.  With P0 = P1 = 0 and v = 0 throughout this is
    the simple quotient Q[t]/(F)."""

    def __init__(self, F, P0, P1):
        self.F = fmpq_poly(F)
        if self.F.degree() < 1:
            raise ValueError("F must have positive degree")
        self.P0 = fmpq_poly(P0) % self.F
        self.P1 = fmpq_poly(P1) % self.F

    @staticmethod
    def _poly(x):
        if isinstance(x, fmpq_poly):
            return x
        return fmpq_poly([frac_to_fmpq(c) for c in x])

    def elem(self, u, v=None):
        if v is None:
            v = fmpq_poly([])
        return KElem(self, self._poly(u) % self.F, self._poly(v) % self.F)

    def from_rational(self, x):
        return KElem(self, fmpq_poly([frac_to_fmpq(x)]), fmpq_poly([]))

    def from_strings(self, u_coeffs, v_coeffs):
        return self.elem(poly_from_strings(u_coeffs), poly_from_strings(v_coeffs))


class KElem:
    __slots__ = ("R", "u", "v")

    def __init__(self, R, u, v):
        self.R = R
        self.u = u
        self.v = v

    def is_zero(self):
        return self.u.is_zero() and self.v.is_zero()

    def __add__(self, o):
        return KElem(self.R, self.u + o.u, self.v + o.v)

    def __sub__(self, o):
        return KElem(self.R, self.u - o.u, self.v - o.v)

    def __neg__(self):
        return KElem(self.R, -self.u, -self.v)

    def __mul__(self, o):
        R = self.R
        F = R.F
        vv = self.v * o.v
        if vv.is_zero():
            u = (self.u * o.u) % F
            v = (self.u * o.v + self.v * o.u) % F
        else:
            u = (self.u * o.u + vv * R.P0) % F
            v = (self.u * o.v + self.v * o.u + vv * R.P1) % F
        return KElem(R, u, v)

    def __repr__(self):
        return f"KElem(u={self.u}, v={self.v})"


